"""Benchmark datapack staging, dependency downloads, and local server preparation."""
from __future__ import annotations

from pathlib import Path
import hashlib
import json
import os
import shutil
import tempfile
import urllib.parse
import urllib.request
import zipfile

from sgp_tools.core_staging import MODULES, validate
from sgp_tools.mixer import install as install_mixer

from . import scenario_schema
from .errors import BenchmarkError
from .settings import CONFIG, ROOT, SERVER_MARKER


def load_staging_scenarios(repository: Path) -> dict[str, dict]:
    scenarios = scenario_schema.load_scenarios(
        repository / 'benchmarks/scenarios', error_type=ValueError
    )
    config = json.loads((repository / 'benchmarks/config.json').read_text(encoding='utf-8'))
    scenario_schema.validate_scenario_graph(
        scenarios, int(config['default_players']), error_type=ValueError
    )
    return scenarios


def function_file(data: Path, identifier: str) -> Path:
    namespace, name = identifier.split(':', 1)
    return data / namespace / 'function' / f'{name}.mcfunction'


def validate_scenario_entrypoints(data: Path, scenarios: dict[str, dict]) -> None:
    """Verify atomic scenario entry points exist in the staged benchmark pack."""
    for scenario in scenarios.values():
        if 'components' in scenario:
            continue
        for key in ('setup', 'tick', 'teardown', 'measurement_prepare', 'measurement_reset'):
            identifier = scenario.get(key)
            if identifier is None:
                continue
            path = function_file(data, identifier)
            if not path.is_file():
                raise ValueError(f'Scenario {scenario["name"]}: missing {key} function {identifier}')


def append_tag_value(path: Path, value: str) -> None:
    document = json.loads(path.read_text(encoding='utf-8'))
    values = document.setdefault('values', [])
    if value not in values:
        values.append(value)
    path.write_text(json.dumps(document, indent=2) + '\n', encoding='utf-8')


def prepare_benchmark_datapack(repository: Path, server: Path) -> None:
    """Stage the plugin-free benchmark datapack into a new server directory."""
    repository = repository.resolve()
    server = server.resolve()
    if server.exists():
        raise ValueError(f'Refusing to overwrite an existing server directory: {server}')

    validate(repository / 'data')
    scenarios = load_staging_scenarios(repository)

    pack = server / 'world/datapacks/SGP-Datapack'
    (pack / 'data').mkdir(parents=True)
    for child in sorted((repository / 'data').iterdir()):
        if child.name in MODULES:
            continue
        target = pack / 'data' / child.name
        if child.is_dir():
            shutil.copytree(child, target)
            shutil.rmtree(target / 'test', ignore_errors=True)
        else:
            shutil.copy2(child, target)
    shutil.copy2(repository / 'pack.mcmeta', pack / 'pack.mcmeta')

    fixtures = repository / 'benchmarks/fixtures/data'
    if not fixtures.is_dir():
        raise ValueError(f'Missing benchmark fixtures: {fixtures}')
    for source in fixtures.rglob('*'):
        if not source.is_file():
            continue
        relative = source.relative_to(fixtures)
        destination = pack / 'data' / relative
        if destination.exists():
            raise ValueError(f'Benchmark fixture collides with production resource: {relative}')
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, destination)

    validate_scenario_entrypoints(pack / 'data', scenarios)
    append_tag_value(pack / 'data/minecraft/tags/function/load.json', 'sgp.bench:load')
    append_tag_value(pack / 'data/minecraft/tags/function/tick.json', 'sgp.bench:tick')
    validate(pack / 'data', core=True)

    (server / 'server.properties').write_text(
        '\n'.join([
            'level-name=world',
            'level-type=minecraft:flat',
            'level-seed=sgp-benchmark',
            'generate-structures=false',
            'spawn-animals=false',
            'spawn-monsters=false',
            'spawn-npcs=false',
            'function-permission-level=4',
            'online-mode=false',
            'spawn-protection=0',
            'view-distance=5',
            'simulation-distance=5',
            'motd=SGP local benchmark server',
            '',
        ]),
        encoding='utf-8',
    )
    (server / 'eula.txt').write_text('eula=true\n', encoding='utf-8')
    (server / SERVER_MARKER).write_text(
        'Generated by .github/scripts/prepare_bench.py; safe for benchmarks/bench.py to rebuild.\n',
        encoding='utf-8',
    )
    print(f'Prepared plugin-free benchmark server at {server}')


def cached_download(url: str, cache_dir: Path, label: str) -> Path:
    cache_dir.mkdir(parents=True, exist_ok=True)
    url_name = Path(urllib.parse.unquote(urllib.parse.urlparse(url).path)).name or label
    safe_label = label.replace('/', '__')
    url_key = hashlib.sha256(url.encode('utf-8')).hexdigest()[:12]
    target = cache_dir / f'{safe_label}--{url_key}--{url_name}'
    if target.is_file() and target.stat().st_size > 0:
        return target
    print(f'Downloading {label} ...')
    fd, temporary_name = tempfile.mkstemp(prefix=target.name + '.', suffix='.part', dir=cache_dir)
    os.close(fd)
    temporary = Path(temporary_name)
    try:
        with urllib.request.urlopen(url) as response, temporary.open('wb') as output:
            shutil.copyfileobj(response, output)
        if temporary.stat().st_size == 0:
            raise BenchmarkError(f'Downloaded empty file for {label}')
        temporary.replace(target)
    except Exception:
        temporary.unlink(missing_ok=True)
        raise
    return target


def verify_zip(path: Path, label: str) -> None:
    try:
        with zipfile.ZipFile(path) as archive:
            bad = archive.testzip()
            if bad:
                raise BenchmarkError(f'{label} is corrupt at {bad}')
    except zipfile.BadZipFile as exc:
        raise BenchmarkError(f'{label} is not a valid jar/zip: {path}') from exc


def prepare_server(server: Path, cache_dir: Path) -> None:
    if server.exists():
        if not (server / SERVER_MARKER).is_file():
            raise BenchmarkError(
                f'Refusing to delete existing directory without {SERVER_MARKER}: {server}'
            )
        shutil.rmtree(server)
    prepare_benchmark_datapack(ROOT, server)

    downloads: dict[str, Path] = {}
    for destination, url in CONFIG['dependencies'].items():
        archive = cached_download(url, cache_dir, destination)
        verify_zip(archive, destination)
        downloads[destination] = archive
        if destination == 'actionbar-mixer.zip':
            continue
        target = server / destination
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(archive, target)

    install_mixer(server, downloads['actionbar-mixer.zip'])
    print(f'Benchmark server ready: {server}')
